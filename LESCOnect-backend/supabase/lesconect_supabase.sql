-- 4. Tabla de Auditoría y Despacho Automático de Alertas SOS 9-1-1
create table if not exists public.emergency_alerts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  user_name text,
  category text not null,
  latitude numeric(10, 7),
  longitude numeric(10, 7),
  accuracy_meters numeric(6, 2),
  maps_url text,
  recipients jsonb not null default '[]'::jsonb,
  message_text text not null,
  status text not null default 'dispatched_by_server',
  created_at timestamptz not null default now()
);

alter table public.emergency_alerts enable row level security;

drop policy if exists "Permitir insercion de alertas sos" on public.emergency_alerts;
create policy "Permitir insercion de alertas sos"
  on public.emergency_alerts
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Usuario ve sus propias alertas sos" on public.emergency_alerts;
create policy "Usuario ve sus propias alertas sos"
  on public.emergency_alerts
  for select
  to authenticated
  using (auth.uid() = user_id);

