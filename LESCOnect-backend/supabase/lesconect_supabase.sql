-- 1. Tabla de Catálogo de Videos (Pública en lectura)
create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  module smallint not null check (module between 1 and 7),
  category text check (category in ('banco', 'emergencia', 'hospital', 'mensajes', 'policia')),
  file_code text not null,
  situation smallint not null default 0,
  sentence smallint not null default 0,
  phrase_es text not null,
  r2_key text not null unique,
  r2_key_vertical text generated always as ('vertical/' || r2_key) stored,
  r2_key_horizontal text generated always as ('horizontal/' || r2_key) stored,
  version integer not null default 1,
  size_bytes bigint,
  duration_s numeric(6,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique nulls not distinct (module, category, file_code)
);

alter table public.videos enable row level security;

drop policy if exists "Catalogo de videos publico" on public.videos;
create policy "Catalogo de videos publico"
  on public.videos
  for select
  to anon, authenticated
  using (true);

create index if not exists videos_module_category_idx
  on public.videos (module, category, situation, sentence);

-- 2. Tabla de Perfiles de Usuario (Protegida con RLS por sesión)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  national_id text unique,
  phone text,
  birth_date date,
  emergency_contact_name text,
  emergency_contact_phone text,
  emergency_contact_relation text,
  emergency_contact_knows_lesco boolean not null default false,
  text_size text not null default 'normal',
  vibration_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "Usuario ve su propio perfil" on public.profiles;
create policy "Usuario ve su propio perfil"
  on public.profiles
  for select
  to authenticated
  using (auth.uid() = id);

drop policy if exists "Usuario actualiza su propio perfil" on public.profiles;
create policy "Usuario actualiza su propio perfil"
  on public.profiles
  for update
  to authenticated
  using (auth.uid() = id);

drop policy if exists "Usuario inserta su propio perfil" on public.profiles;
create policy "Usuario inserta su propio perfil"
  on public.profiles
  for insert
  to authenticated
  with check (auth.uid() = id);

